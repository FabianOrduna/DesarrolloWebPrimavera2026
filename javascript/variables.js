// -------------- let --------------

// Usando let: puedes re-asignar el valor
let contador = 1;
console.log("Inicial con let:", contador); // 1

contador = 2;
console.log("Re-asignado con let:", contador); // 2

// -------------- const --------------

// Usando const: no puedes re-asignar el valor
const PI = 3.1416;
console.log("Inicial con const:", PI); // 3.1416

// PI = 3.14159;
